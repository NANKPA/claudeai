#!/usr/bin/env python3
"""Render the YAML registries into human/Claude-readable markdown tables.

Generated files carry no frontmatter (so they never become graph nodes) and a
"generated" banner: edit the YAML, then re-run this script.
"""
from __future__ import annotations

import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ti_lib import KB_ROOT, load_kb  # noqa: E402

BANNER = "<!-- generated by tools/render_registries.py from the YAML registries; do not edit by hand -->\n\n"


def esc(text) -> str:
    return str(text or "").replace("|", "\\|").replace("\n", " ")


def write(rel: str, content: str) -> None:
    path = KB_ROOT / rel
    path.write_text(BANNER + content.rstrip() + "\n", encoding="utf-8")
    print(f"wrote {rel}")


def main() -> None:
    kb = load_kb()
    nodes = kb.nodes
    out_edges: dict[str, list] = defaultdict(list)
    in_edges: dict[str, list] = defaultdict(list)
    for e in kb.edges:
        out_edges[e.source].append(e)
        in_edges[e.target].append(e)

    def targets(nid: str, relation: str) -> list[str]:
        return [e.target for e in out_edges[nid] if e.relation == relation]

    def sources(nid: str, relation: str) -> list[str]:
        return [e.source for e in in_edges[nid] if e.relation == relation]

    def labels(ids) -> str:
        return ", ".join(esc(nodes[i].label) for i in ids if i in nodes)

    def concept_links(ids) -> str:
        return ", ".join(f"`{i}`" for i in ids if i in nodes)

    # ── 05 books ──
    books = sorted((n for n in nodes.values() if n.kind == "book" and "rank" in n.attrs), key=lambda n: n.attrs["rank"])
    lines = ["# Top 100 Trading Books\n",
             "Ranking method: see the header of `books.yaml`. Each row links to concept ids in `07_concepts/`; "
             "*Builds on* shows the book-to-book lineage.\n",
             "| # | Title | Author | Year | Category | Key idea | Builds on | Concepts |",
             "|---|---|---|---|---|---|---|---|"]
    for b in books:
        a = b.attrs
        lines.append(f"| {a['rank']} | **{esc(b.label)}** | {esc(a.get('author'))} | {a.get('year', '')} | {esc(a.get('category'))} | "
                     f"{esc(a.get('key_idea'))} | {labels(targets(b.id, 'derived_from'))} | {concept_links(targets(b.id, 'covers'))} |")
    cats = Counter(b.attrs.get("category") for b in books)
    lines += ["\n## By category\n", "| Category | Count | Titles |", "|---|---|---|"]
    for cat, count in cats.most_common():
        titles = "; ".join(esc(b.label) for b in books if b.attrs.get("category") == cat)
        lines.append(f"| {esc(cat)} | {count} | {titles} |")
    cover_counts = Counter(t for b in books for t in targets(b.id, "covers"))
    lines += ["\n## Most-covered concepts across the 100 books\n", "| Concept | # books |", "|---|---|"]
    for cid, count in cover_counts.most_common(20):
        lines.append(f"| {esc(nodes[cid].label)} (`{cid}`) | {count} |")
    write("05_books-top-100/top-100-trading-books.md", "\n".join(lines))

    # ── 06 math books & lectures ──
    tracks = [n for n in nodes.values() if n.kind == "track"]
    math = [n for n in nodes.values() if n.kind in ("mathbook", "paper")]
    lines = ["# Mathematics Canon for Analysis & Execution\n",
             "Levels: 1 = accessible · 2 = undergraduate · 3 = graduate/research.\n"]
    for t in sorted(tracks, key=lambda n: n.id):
        members = sorted((m for m in math if t.id in targets(m.id, "part_of")), key=lambda m: (m.attrs.get("level", 9), m.attrs.get("year", 0)))
        lines += [f"\n## {esc(t.label)}\n", "| Level | Title | Author | Year | Key idea | Concepts |", "|---|---|---|---|---|---|"]
        for m in members:
            a = m.attrs
            lines.append(f"| {a.get('level', '')} | **{esc(m.label)}** | {esc(a.get('author'))} | {a.get('year', '')} | {esc(a.get('key_idea'))} | {concept_links(targets(m.id, 'covers'))} |")
    write("06_mathematics-foundations/math-books.md", "\n".join(lines))

    def media_table(title: str, rel_yaml: str) -> str:
        data = yaml.safe_load((KB_ROOT / rel_yaml).read_text(encoding="utf-8")) or {}
        ids = {m["id"] for m in data.get("media", []) if isinstance(m, dict) and "id" in m}
        items = [nodes[i] for i in ids if i in nodes]
        rows = ["| Title | Speakers | Year | Format | Verification | Concepts | Link |", "|---|---|---|---|---|---|---|"]
        for m in sorted(items, key=lambda n: (n.attrs.get("verification") != "verified", n.label)):
            a = m.attrs
            url = a.get("url") or next((s.get("url") for s in a.get("sources", []) if isinstance(s, dict)), "")
            link = f"[link]({url})" if url else ""
            rows.append(f"| **{esc(m.label)}** | {labels(targets(m.id, 'features_speaker'))} | {a.get('year', '')} | {esc(a.get('format'))} | "
                        f"{esc(a.get('verification'))} | {concept_links(targets(m.id, 'covers'))} | {link} |")
        return f"# {title}\n\n" + "\n".join(rows)

    def queries_block(rel_yaml: str) -> str:
        data = yaml.safe_load((KB_ROOT / rel_yaml).read_text(encoding="utf-8")) or {}
        dq = data.get("discovery_queries") or {}
        if not dq:
            return ""
        out = ["\n## Discovery queries (scraper fills the ranked top-100 from these)\n"]
        for group, qs in dq.items():
            out.append(f"- **{group}**: " + "; ".join(f"`{q}`" for q in qs))
        return "\n".join(out)

    write("06_mathematics-foundations/lectures.md",
          media_table("Math-of-Trading Lectures, Courses & Talks (seed)", "06_mathematics-foundations/lectures.yaml")
          + "\n" + queries_block("06_mathematics-foundations/lectures.yaml"))
    write("02_podcasts-interviews/landmark-media.md",
          media_table("Landmark Trading Interviews, Talks & Episodes (seed)", "02_podcasts-interviews/landmark-media.yaml")
          + "\n" + queries_block("02_podcasts-interviews/landmark-media.yaml"))

    # ── 02 podcasts ──
    pods = sorted((n for n in nodes.values() if n.kind == "podcast"), key=lambda n: n.label)
    lines = ["# Podcast Directory\n", "| Podcast | Hosts | Focus | Rank signal | Concepts |", "|---|---|---|---|---|"]
    for p in pods:
        a = p.attrs
        lines.append(f"| **{esc(p.label)}** | {labels(targets(p.id, 'hosted_by'))} | {esc(a.get('focus'))} | {esc(a.get('rank_signal'))} | {concept_links(targets(p.id, 'covers'))} |")
    write("02_podcasts-interviews/podcast-directory.md", "\n".join(lines))

    # ── 03 people ──
    people = sorted((n for n in nodes.values() if n.kind == "person" and not n.auto), key=lambda n: n.label)
    lines = ["# People Directory: legends, authors, researchers, hosts, guests\n",
             "*Influenced by* entries marked † are inferred (plausible, not explicitly documented).\n",
             "| Person | Role | Era | Known for | Influenced by | Teaches | Authored | Featured in |", "|---|---|---|---|---|---|---|---|"]
    for p in people:
        a = p.attrs
        infl = ", ".join(esc(nodes[e.target].label) + (" †" if e.inferred else "") for e in out_edges[p.id] if e.relation == "influenced_by")
        authored = labels(sources(p.id, "authored_by"))
        lines.append(f"| **{esc(p.label)}** | {esc(a.get('role'))} | {esc(a.get('era'))} | {esc(a.get('known_for'))} | {infl} | "
                     f"{concept_links(targets(p.id, 'teaches'))} | {authored} | {labels(targets(p.id, 'featured_in'))} |")
    auto = sorted(n.label for n in nodes.values() if n.kind == "person" and n.auto)
    lines += ["\n## Additional authors (auto-linked from book registries)\n", ", ".join(auto)]
    write("03_legends-authorities/people-directory.md", "\n".join(lines))

    # ── 01 Chart Fanatics catalog & concept frequency ──
    cf_strats = sorted((n for n in nodes.values() if n.kind == "strategy"), key=lambda n: n.label)
    lines = ["# Chart Fanatics — Strategy & Video Catalog (seed)\n",
             "## Strategies / playbooks\n", "| Strategy | Trader | Status | Uses concepts |", "|---|---|---|---|"]
    for s in cf_strats:
        lines.append(f"| **{esc(s.label)}** | {labels(targets(s.id, 'taught_by'))} | {esc(s.attrs.get('status'))} | {concept_links(targets(s.id, 'uses'))} |")
    cf_media = [n for n in nodes.values() if n.kind == "media" and n.source_file == "01_chart-fanatics/catalog.yaml"]
    lines += ["\n## Known videos & episodes\n", "| Title | Channel | Speakers | ~Views | Verification |", "|---|---|---|---|---|"]
    for m in sorted(cf_media, key=lambda n: -(n.attrs.get("views_approx") or 0)):
        views = f"{m.attrs['views_approx']:,}" if m.attrs.get("views_approx") else ""
        lines.append(f"| **{esc(m.label)}** | {labels(targets(m.id, 'featured_in'))} | {labels(targets(m.id, 'features_speaker'))} | {views} | {esc(m.attrs.get('verification'))} |")
    write("01_chart-fanatics/video-catalog.md", "\n".join(lines))

    usage = Counter(t for s in cf_strats if "channel_chart_fanatics" in targets(s.id, "featured_in") for t in targets(s.id, "uses"))
    lines = ["# Chart Fanatics — concept frequency across guest strategies\n",
             "How many Chart Fanatics strategy notes `uses:` each concept. This is a proxy for what the channel teaches most.\n",
             "| Concept | # strategies | Strategies |", "|---|---|---|"]
    for cid, count in usage.most_common():
        users = ", ".join(esc(nodes[s.id].label.split(' — ')[0]) for s in cf_strats if cid in targets(s.id, "uses"))
        lines.append(f"| {esc(nodes[cid].label)} (`{cid}`) | {count} | {users} |")
    write("01_chart-fanatics/concept-frequency.md", "\n".join(lines))

    # ── scraped lists (only when the scrapers have run) ──
    def fmt_dur(sec) -> str:
        sec = int(sec or 0)
        return f"{sec // 3600}:{sec % 3600 // 60:02d}:{sec % 60:02d}" if sec >= 3600 else f"{sec // 60}:{sec % 60:02d}"

    def scraped(rel_yaml: str) -> list[dict]:
        path = KB_ROOT / rel_yaml
        return (yaml.safe_load(path.read_text(encoding="utf-8")) or {}).get("scraped_media", []) if path.exists() else []

    cf_cat = scraped("01_chart-fanatics/catalog.scraped.yaml")
    if cf_cat:
        longs = sorted((v for v in cf_cat if v.get("tab") == "videos"), key=lambda v: -(v.get("view_count") or 0))
        shorts = [v for v in cf_cat if v.get("tab") == "shorts"]
        hours = sum(v.get("duration_s") or 0 for v in longs) / 3600
        lines = [f"\n## Full channel catalog (scraped)\n",
                 f"{len(cf_cat):,} uploads: **{len(longs)} long-form masterclasses (~{hours:.0f} hours)** and {len(shorts):,} shorts "
                 "(shorts are listed in `catalog.scraped.yaml`). View counts are as listed on the channel at scrape time.\n",
                 "| # | Title | Views | Length | Concepts (from title) |", "|---|---|---|---|---|"]
        for k, v in enumerate(longs, 1):
            views = f"{v['view_count']:,}" if v.get("view_count") else ""
            lines.append(f"| {k} | [{esc(v['title'])}]({v['url']}) | {views} | {fmt_dur(v.get('duration_s'))} | {concept_links(v.get('covers') or [])} |")
        vc = KB_ROOT / "01_chart-fanatics/video-catalog.md"
        vc.write_text(vc.read_text(encoding="utf-8").rstrip() + "\n" + "\n".join(lines) + "\n", encoding="utf-8")
        print("appended channel catalog to 01_chart-fanatics/video-catalog.md")

    def top_table(rel_yaml: str, md_rel: str, title: str) -> None:
        items = scraped(rel_yaml)
        if not items:
            return
        as_of = items[0].get("views_as_of", "")
        lines = [f"\n## {title}\n",
                 f"Ranked by YouTube views{f' (as of {as_of})' if as_of else ''} after filtering: no audiobook/summary re-uploads, "
                 "title must match the query, at most 4 picks per query. Generated by `tools/scrapers/youtube_top_search.py` (T3: discovery list).\n",
                 "| # | Title | Channel | Views | Concepts |", "|---|---|---|---|---|"]
        for v in items:
            views = f"{v['views']:,}" if v.get("views") else ""
            lines.append(f"| {v['rank']} | [{esc(v['title'])}]({v['url']}) | {esc(v.get('channel'))} | {views} | {concept_links(v.get('covers') or [])} |")
        md = KB_ROOT / md_rel
        md.write_text(md.read_text(encoding="utf-8").rstrip() + "\n" + "\n".join(lines) + "\n", encoding="utf-8")
        print(f"appended top list to {md_rel}")

    top_table("02_podcasts-interviews/landmark-media.scraped.yaml", "02_podcasts-interviews/landmark-media.md", "Top 100 trading interviews & podcast videos (scraped)")
    top_table("06_mathematics-foundations/lectures.scraped.yaml", "06_mathematics-foundations/lectures.md", "Top math-of-trading videos (scraped)")

    eps = scraped("02_podcasts-interviews/podcast-episodes.scraped.yaml")
    if eps:
        per_show = Counter(x for e in eps for x in e.get("featured_in") or [])
        guests = defaultdict(list)
        for e in eps:
            for pid in e.get("speaker_ids") or []:
                guests[pid].append(e)
        lines = ["\n## Episode catalogs (scraped from RSS)\n", "| Podcast | Episodes saved |", "|---|---|"]
        lines += [f"| {esc(nodes[k].label) if k in nodes else k} | {v:,} |" for k, v in per_show.most_common()]
        lines += ["\n## Episodes featuring people in this knowledge base\n",
                  "Guests detected in episode titles/show notes (show hosts and repeated sponsor/advert lines excluded).\n",
                  "| Person | Episodes | Examples |", "|---|---|---|"]
        for pid, lst in sorted(guests.items(), key=lambda kv: -len(kv[1])):
            if pid not in nodes:
                continue
            ex = "; ".join(f"{esc(e['title'])} ({esc(nodes[e['featured_in'][0]].label) if e.get('featured_in') and e['featured_in'][0] in nodes else ''})" for e in lst[:3])
            lines.append(f"| {esc(nodes[pid].label)} | {len(lst)} | {ex} |")
        pd = KB_ROOT / "02_podcasts-interviews/podcast-directory.md"
        pd.write_text(pd.read_text(encoding="utf-8").rstrip() + "\n" + "\n".join(lines) + "\n", encoding="utf-8")
        print("appended episode catalogs to 02_podcasts-interviews/podcast-directory.md")

    # ── KB-wide manifest ──
    by_kind = Counter(n.kind for n in nodes.values())
    by_part = Counter(n.source_file.split("/")[0] for n in nodes.values() if not n.auto)
    lines = ["# Knowledge Base Manifest\n", f"- Nodes: **{len(nodes)}** · Edges: **{len(kb.edges)}**",
             f"- Inferred (lower-confidence) edges: {sum(e.inferred for e in kb.edges)}",
             f"- Dangling references: {len(kb.errors)}\n",
             "| Kind | Count |", "|---|---|"] + [f"| {k} | {v} |" for k, v in by_kind.most_common()]
    lines += ["\n| Partition | Nodes defined |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(by_part.items())]
    write("MANIFEST.md", "\n".join(lines))
    if kb.errors:
        print("\n".join(kb.errors), file=sys.stderr)


if __name__ == "__main__":
    main()

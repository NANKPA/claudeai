#!/usr/bin/env python3
"""Package the knowledge base for Claude.

Writes to dist/:
  trading-intelligence-bundle.md        everything (notes, registry tables, graph report) in partition order
  trading-intelligence-core.md          the same without the 47 full playbook notes and the long catalogs
                                        (fits one context window; add partitions/01_chart-fanatics.md when needed)
  partitions/<partition>.md             one bundle per partition (for selective upload)
  CLAUDE_PROJECT_INSTRUCTIONS.md        paste into a Claude Project's instructions
  graph-summary.json                    compact graph (ids, labels, kinds, communities, typed edges)

Usage: python3 tools/bundle_for_claude.py [--include-raw]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ti_lib import KB_ROOT, REPO_ROOT  # noqa: E402

DIST = REPO_ROOT / "dist"
SKIP_DIRS = {"09_knowledge-graph", "graphify-out"}
GRAPH_FILES = ["09_knowledge-graph/GRAPH_REPORT.md", "09_knowledge-graph/BUILD_REPORT.md"]
# The owner's philosophy is the foundation: its partition goes first, in reading order.
FIRST_PARTITION = "00_philosophy"
PHILO_ORDER = ["README.md", "philosophy-of-the-relationship.md", "decision-protocol.md", "journal-template.md",
               "centrality-report.md", "strategy-alignment.md", "evidence-lab.md",
               "hypotheses.md", "research-program.md", "extensions.md", "blueprint-map.md",
               "strategy-alignment-evidence.md"]
# Left out of the core bundle (still in the full bundle and the partition files).
CORE_EXCLUDE = ("01_chart-fanatics/strategies/", "01_chart-fanatics/video-catalog.md", "01_chart-fanatics/concept-frequency.md",
                "03_legends-authorities/people.yaml", "03_legends-authorities/people-directory.md",
                "02_podcasts-interviews/podcast-episodes", "02_podcasts-interviews/podcast-directory.md",
                "02_podcasts-interviews/landmark-media.md", "06_mathematics-foundations/lectures.md",
                "05_books-top-100/books.yaml",                       # top-100-trading-books.md carries it
                "00_philosophy/blueprint-map.md",                    # link rationale; the links are in the graph
                "00_philosophy/strategy-alignment-evidence.md")


def partition_files(part: Path, include_raw: bool) -> list[Path]:
    files = []
    for p in sorted(part.rglob("*")):
        if not p.is_file() or p.suffix not in (".md", ".yaml"):
            continue
        rel = p.relative_to(part).as_posix()
        if rel.startswith("raw/") and not include_raw:
            continue
        if p.suffix == ".yaml" and (p.with_suffix(".md").exists() or p.name.endswith(".scraped.yaml")
                                    or p.name in ("books.enriched.yaml", "blueprint.yaml")):
            continue  # a rendered markdown file already carries this registry (blueprint.yaml -> blueprint-map.md)
        files.append(p)
    # README first, then notes (the philosophy partition in its own reading order)
    rank = {name: i for i, name in enumerate(PHILO_ORDER)} if part.name == FIRST_PARTITION else {"README.md": 0}
    files.sort(key=lambda p: (rank.get(p.relative_to(part).as_posix(), len(rank)), p.as_posix()))
    return files


def section(path: Path) -> str:
    rel = path.relative_to(KB_ROOT).as_posix()
    text = path.read_text(encoding="utf-8").strip()
    if path.suffix == ".yaml":
        text = f"```yaml\n{text}\n```"
    return f"\n\n<!-- ===== FILE: trading-intelligence/{rel} ===== -->\n\n{text}\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--include-raw", action="store_true", help="also bundle scraped transcripts/lessons")
    args = ap.parse_args()

    (DIST / "partitions").mkdir(parents=True, exist_ok=True)
    head = [KB_ROOT / "README.md", KB_ROOT / "CLAUDE.md", KB_ROOT / "MANIFEST.md"]
    whole = ["# Trading Intelligence — full knowledge bundle\n",
             "Generated by tools/bundle_for_claude.py. Each file is delimited by a `FILE:` marker with its repo path.\n"]
    whole += [section(p) for p in head if p.exists()]
    core = list(whole)
    core[0] = "# Trading Intelligence — core knowledge bundle\n"
    for part in sorted((p for p in KB_ROOT.iterdir() if p.is_dir() and p.name not in SKIP_DIRS),
                       key=lambda p: (p.name != FIRST_PARTITION, p.name)):
        chunks = [section(p) for p in partition_files(part, args.include_raw)]
        (DIST / "partitions" / f"{part.name}.md").write_text(f"# Partition {part.name}\n" + "".join(chunks), encoding="utf-8")
        whole += chunks
        core += [section(p) for p in partition_files(part, False)
                 if not p.relative_to(KB_ROOT).as_posix().startswith(CORE_EXCLUDE)]
    whole += [section(KB_ROOT / g) for g in GRAPH_FILES if (KB_ROOT / g).exists()]
    core += [section(KB_ROOT / GRAPH_FILES[1])] if (KB_ROOT / GRAPH_FILES[1]).exists() else []
    (DIST / "trading-intelligence-core.md").write_text("".join(core), encoding="utf-8")
    bundle = "".join(whole)
    (DIST / "trading-intelligence-bundle.md").write_text(bundle, encoding="utf-8")
    (DIST / "CLAUDE_PROJECT_INSTRUCTIONS.md").write_text((KB_ROOT / "CLAUDE.md").read_text(encoding="utf-8"), encoding="utf-8")

    graph = KB_ROOT / "09_knowledge-graph" / "graph.json"
    if graph.exists():
        g = json.loads(graph.read_text(encoding="utf-8"))
        summary = {
            "nodes": [{k: n.get(k) for k in ("id", "label", "kind", "layer", "community", "community_name", "source_file")} for n in g["nodes"]],
            "edges": [[e["source"], e["relation"], e["target"]] for e in g.get("links", g.get("edges", []))],
        }
        (DIST / "graph-summary.json").write_text(json.dumps(summary, ensure_ascii=False), encoding="utf-8")
    words = len(bundle.split())
    print(f"dist/trading-intelligence-bundle.md: {len(bundle) / 1024:.0f} KB, ~{words:,} words (~{int(words * 1.4):,} tokens)")
    cw = len("".join(core).split())
    print(f"dist/trading-intelligence-core.md: ~{cw:,} words (~{int(cw * 1.4):,} tokens)")
    for p in sorted((DIST / "partitions").glob("*.md")):
        print(f"  partitions/{p.name}: {p.stat().st_size / 1024:.0f} KB")


if __name__ == "__main__":
    main()
